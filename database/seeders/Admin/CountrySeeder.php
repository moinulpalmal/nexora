    /**
     * Add every ISO country whose codes and name are still free.
     */
    public function run(): void
    {
        $taken = Country::withTrashed()->get(['name', 'iso2', 'iso3']);

        $names = $taken->mapWithKeys(fn (Country $country): array => [mb_strtolower($country->name) => true])->all();
