        $iso3s = $taken->mapWithKeys(fn (Country $country): array => [mb_strtoupper($country->iso3) => true])->all();

        $now = now();
        $rows = [];

        foreach (self::COUNTRIES as [$iso2, $iso3, $numeric, $name, $dial, $currency, $nationality]) {
            if (isset($iso2s[$iso2]) || isset($iso3s[$iso3]) || isset($names[mb_strtolower($name)])) {
                continue;
            }

            $rows[] = [
                'name' => $name,
                'iso2' => $iso2,
                'iso3' => $iso3,
                'numeric_code' => $numeric,
                'dial_code' => $dial,
                'currency_code' => $currency,
                'nationality' => $nationality,
                'status' => RecordStatus::Active->value,
                'created_at' => $now,
                'updated_at' => $now,
            ];
        }

        foreach (array_chunk($rows, 100) as $chunk) {
            Country::query()->insert($chunk);
        }
    }
