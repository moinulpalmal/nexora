<?php

namespace App\Console\Commands;

use App\Enums\EnumRegistry;
use App\Enums\Theme;
use Illuminate\Console\Attributes\Description;
use Illuminate\Console\Attributes\Signature;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\Process;

/**
 * Regenerate `resources/js/lib/enums.ts` from {@see EnumRegistry}.
 *
 * The second generated frontend surface beside Wayfinder (ARCHITECTURE.md
 * §8.2), and it takes the same rule: **never hand-edit the output.** Change
 * the PHP enum, run this, commit both.
 *
 * `tests/Feature/EnumRegistryTest.php` renders the same content this command
 * writes and diffs it against the committed file, so a PHP enum changed
 * without re-running this command fails the suite rather than silently
 * drifting — the exact failure this whole change exists to close off.
 */
#[Signature('enums:sync')]
#[Description('Regenerate resources/js/lib/enums.ts from App\Enums\EnumRegistry.')]
class SyncEnums extends Command
{
    public function handle(): int
    {
        $path = resource_path('js/lib/enums.ts');

        file_put_contents($path, self::render());

        $this->components->info('Regenerated '.$path);

        $formatted = Process::path(base_path())->run(['npx', 'prettier', '--write', 'resources/js/lib/enums.ts']);

        if ($formatted->successful()) {
            $this->components->info('Formatted with prettier.');
        } else {
            $this->components->warn('prettier did not run — install/format the generated file before committing.');
        }

        return self::SUCCESS;
    }

    /**
     * The generated file's full contents, deterministic for a given registry
     * state — this is what {@see EnumRegistryTest} diffs against.
     */
    public static function render(): string
    {
        $lines = [
            '// Generated by `php artisan enums:sync`. Do not edit — ARCHITECTURE.md §8.2.',
            '//',
            '// Source: `App\\Enums\\EnumRegistry`. One block per registered enum, in',
            '// registry order. An unlabelled enum gets its value map only — no `_LABELS`,',
            '// because nothing labels it in PHP either.',
            '',
        ];

        foreach (EnumRegistry::toArray() as $enum) {
            array_push($lines, ...self::renderEnum($enum));
        }

        array_push($lines, ...self::renderThemeModes());

        return implode("\n", $lines)."\n";
    }

    /**
     * One enum's block: the value map, its derived type, and — when
     * labelled — the label map keyed by value.
     *
     * @param  array{class: class-string, id: string, name: string, group: string, labelled: bool, cases: list<array{case: string, value: int|string, label: ?string}>}  $enum
     * @return list<string>
     */
    private static function renderEnum(array $enum): array
    {
        $constName = str_replace('-', '_', strtoupper($enum['id']));
        $typeName = $enum['name'];

        $lines = [
            "export const {$constName} = {",
        ];

        foreach ($enum['cases'] as $case) {
            $lines[] = "    {$case['case']}: ".self::renderValue($case['value']).',';
        }

        $lines[] = '} as const;';
        $lines[] = '';
        $lines[] = "export type {$typeName} = (typeof {$constName})[keyof typeof {$constName}];";
        $lines[] = '';

        if ($enum['labelled']) {
            $lines[] = "export const {$constName}_LABELS: Record<{$typeName}, string> = {";

            foreach ($enum['cases'] as $case) {
                $lines[] = '    '.self::renderKey($case['value']).': '.self::renderValue($case['label']).',';
            }

            $lines[] = '};';
            $lines[] = '';
        }

        return $lines;
    }

    /**
     * `Theme`'s `isDark()`, the one piece of per-case metadata no other enum
     * carries — kept as its own block rather than a generic mechanism built
     * for a single caller. Replaces `lib/themes.ts`'s hand-written `mode` per
     * theme; `lib/themes.ts` imports this rather than restating it.
     *
     * @return list<string>
     */
    private static function renderThemeModes(): array
    {
        $lines = [
            "export const THEME_MODES: Record<Theme, 'light' | 'dark'> = {",
        ];

        foreach (Theme::cases() as $theme) {
            $lines[] = '    '.self::renderKey($theme->value).': '.self::renderValue($theme->isDark() ? 'dark' : 'light').',';
        }

        $lines[] = '};';
        $lines[] = '';

        return $lines;
    }

    private static function renderValue(int|string|null $value): string
    {
        return is_int($value) ? (string) $value : var_export((string) $value, true);
    }

    private static function renderKey(int|string $value): string
    {
        return is_int($value) ? (string) $value : var_export((string) $value, true);
    }
}
